// Local PostgreSQL: real baseline RLS, moderation trigger, private ownership migration.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
const {PGlite}=await import(pathToFileURL(process.env.PGLITE_MODULE).href);
const db=new PGlite();
const id=n=>`00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const author=id(1),reader=id(2),moderator=id(3);
const run=sql=>db.exec(sql);
const as=async uid=>run(`reset role; set request.jwt.claim.sub='${uid}'; set role authenticated;`);
const scalar=async sql=>Object.values((await db.query(sql)).rows[0])[0];
try {
 await run(`create role authenticated; create role anon; create role service_role; create schema auth;
 create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth,public to authenticated,anon;`);
 const schema=fs.readFileSync('supabase/schema.sql','utf8');
 const tables=['app_config','profiles','posts','blocked_users','comments','reports'];
 for(const table of tables){
   await run(schema.match(new RegExp(`CREATE TABLE ${table} \\([\\s\\S]*?\\n\\);`))[0]);
   await run(`alter table ${table} enable row level security; grant select,insert,update,delete on ${table} to authenticated;`);
 }
 for(const match of schema.matchAll(/CREATE POLICY[\s\S]*?;/g))if(tables.some(t=>new RegExp(`ON (?:public\\.)?${t}\\s`,'i').test(match[0])))await run(match[0]);
 await run(schema.match(/CREATE OR REPLACE FUNCTION public.enforce_post_moderation\(\)[\s\S]*?\$\$;/)[0]);
 await run(`create trigger enforce_post_moderation before insert or update on posts for each row execute function enforce_post_moderation();
 alter table posts add column audience_colectivo_id uuid;
 create table staff_activity(actor_id uuid,target_id uuid,action text);
 create table notifications(recipient_id uuid,actor_id uuid,kind text,post_id uuid,comment_id uuid,unique(recipient_id,comment_id));
 alter table notifications enable row level security; grant select on notifications to authenticated;
 create policy recipient_read on notifications for select to authenticated using(recipient_id=auth.uid());`);
 await run(fs.readFileSync('supabase/community_questions.sql','utf8'));
 for(const [uid,name,mod] of [[author,'author',false],[reader,'reader',false],[moderator,'mod',true]])await run(`insert into auth.users values('${uid}'); insert into profiles(id,username,is_moderator) values('${uid}','${name}',${mod})`);
 await as(author);
 const publish=(n,anonymous=true)=>scalar(`select publish_question('¿qué escuchas?','contexto',${anonymous},'${id(n)}')`);
 const anonymous=await publish(10), signed=await publish(11,false);
 assert.equal(await publish(10),anonymous,'retry returns same post');
 await assert.rejects(run('select * from question_owners'));
 await assert.rejects(run(`insert into posts(type,author_id) values('pregunta','${author}')`));
 await run(`update posts set title='changed' where id='${signed}'`);
 assert.equal(await scalar(`select title from posts where id='${signed}'`),'¿qué escuchas?');
 await as(reader);
 const row=(await db.query(`select p.*,pr.username from posts p left join profiles pr on pr.id=p.author_id where p.id='${anonymous}'`)).rows[0];
 assert.equal(row.author_id,null);assert.equal(row.username,null);
 assert.equal(JSON.stringify(row).includes(author),false,'public payload has no original author ID');
 assert.equal(await scalar(`select owns_question('${anonymous}')`),false);
 await assert.rejects(run('select * from question_owners'));
 await assert.rejects(run(`select question_author_for_moderation('${anonymous}')`));
 await assert.rejects(run(`select delete_my_question('${anonymous}')`));
 await run(`insert into comments(post_id,author_id,body) values('${anonymous}','${reader}','respuesta firmada');
 insert into reports(reporter_id,post_id,reason) values('${reader}','${anonymous}','spam');`);
 assert.equal(await scalar(`select author_id from comments where post_id='${anonymous}'`),reader);
 assert.equal(await scalar('select count(*) from notifications'),0,'reply does not expose creator through notifications');
 await assert.rejects(run(`insert into comments(post_id,author_id,body) values('${anonymous}',null,'anonymous')`));
 await run(`select block_question_author('${anonymous}')`);
 assert.equal(await scalar(`select count(*) from posts where id in ('${anonymous}','${signed}')`),0,'blocks both signed and anonymous questions from the account');
 await assert.rejects(run('select * from question_blocks'));
 await assert.rejects(run(`insert into comments(post_id,author_id,body) values('${anonymous}','${reader}','blocked reply')`));
 await as(moderator);
 assert.equal(await scalar(`select question_author_for_moderation('${anonymous}')`),author);
 await run('reset role'); assert.equal(await scalar('select count(*) from staff_activity'),1);
 await as(author);
 assert.equal(await scalar(`select count(*) from notifications where post_id='${anonymous}'`),1,'anonymous creator receives reply notification');
 assert.equal(await scalar(`select owns_question('${anonymous}')`),true);
 await run(`select delete_my_question('${anonymous}')`);
 await publish(12);
 await assert.rejects(publish(13),/3 preguntas/,'deleting does not bypass the daily limit');
 await assert.rejects(publish(10),/eliminada/);
 await as(reader);
 const another=await publish(14);
 await run(`insert into blocked_users(blocker_id,blocked_id) values('${reader}','${author}')`);
 await as(author);assert.equal(await scalar(`select count(*) from posts where id='${another}'`),0,'ordinary blocks also protect questions');
 await run(`reset role; set role anon;`);
 await assert.rejects(run(`select publish_question('test','',true,'${id(99)}')`));
 console.log('PASS: anonymous payload, ownership isolation, signed replies, reporting, blocking, audit, idempotency and rate limits');
} finally {await db.close();}
